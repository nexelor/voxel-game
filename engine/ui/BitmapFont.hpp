// Returns a pointer to the 8 bitmap rows for ASCII character c.
// Returns the '?' glyph for out-of-range characters.
inline const uint8_t* FontGlyph(char c) {
    const int idx = static_cast<int>(static_cast<unsigned char>(c)) - FONT_FIRST;
    if (idx < 0 || idx >= FONT_COUNT) {
        // '?' = index of 63-32 = 31
        return FONT_BITMAP[31];
    }
    return FONT_BITMAP[idx];
}
